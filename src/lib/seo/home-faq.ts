/** FAQ 목록 → schema.org FAQPage 노드 (@context 없음 — 호출부의 @graph 에 넣는다). */
export function faqPageNode(id: string, entries: FaqEntry[], extra: Record<string, unknown> = {}) {
  return {
    '@type': 'FAQPage',
    '@id': id,
    inLanguage: 'ko-KR',
    ...extra,
    mainEntity: entries.map((f) => ({
      '@type': 'Question',
      name: f.q,
      acceptedAnswer: { '@type': 'Answer', text: f.a },
    })),
  };
}
