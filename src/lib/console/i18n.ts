export const CONSOLE_DICT: Record<ConsoleLang, Dict> = { ko, en };

export type TranslateVars = Record<string, string | number>;

function lookup(dict: Dict, key: string): string | undefined {
  let cur: string | Dict | undefined = dict;
  for (const part of key.split('.')) {
    if (!cur || typeof cur === 'string') return undefined;
    cur = cur[part];
  }
  return typeof cur === 'string' ? cur : undefined;
}

/** Text for a dotted key; falls back to Korean, then to the key itself. */
export function translate(lang: ConsoleLang, key: string, vars?: TranslateVars): string {
  let s = lookup(CONSOLE_DICT[lang], key) ?? lookup(CONSOLE_DICT.ko, key);
  if (s === undefined) return key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** All leaf keys of a dictionary as dotted paths, sorted. */
export function dictKeys(dict: Dict, prefix = ''): string[] {
  return Object.entries(dict)
    .flatMap(([k, v]) => (typeof v === 'string' ? [prefix + k] : dictKeys(v, `${prefix}${k}.`)))
    .sort();
}

/** The English field when viewing in English and it is filled in, otherwise the Korean one. */
export function localized<T extends object>(lang: ConsoleLang, obj: T, field: string): string {
  const rec = obj as Record<string, unknown>;
  const en = rec[`${field}_en`];
  if (lang === 'en' && typeof en === 'string' && en) return en;
  const base = rec[field];
  return typeof base === 'string' ? base : '';
}

/** First visit is Korean; a remembered 'en' stays English. */
export function resolveLang(stored: unknown): ConsoleLang {
  return stored === 'en' ? 'en' : 'ko';
}
